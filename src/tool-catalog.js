/**
 * Native Tool Catalog — non-MCP capabilities exposed to the chat agent
 * as first-class, selectable tools, on equal footing with SSmcp's tools.
 *
 * Specializations (categories) exist so the agent — and you, scanning
 * the sidebar — can tell at a glance what class of action a tool is
 * and what confirmation/safety behavior to expect:
 *
 *   ui       - live interface changes; always goes through
 *              ChangeConfirmGate (countdown + Keep) on the frontend,
 *              and is refused server-side too if the zone is protected.
 *   browser  - opens a real Chrome window/profile. Fires immediately,
 *              no confirmation gate (it's a new window, not a live swap).
 *   infra    - proxied straight through to SSmcp's existing 47 tools.
 *              Nothing new here, just merged into one list.
 *
 * GET  /api/tools       -> merged list: native tools + SSmcp tools/list
 * POST /api/tools/call  -> dispatch by name; native tools run locally,
 *                          anything else proxies to SSmcp's mcp-api.
 */

