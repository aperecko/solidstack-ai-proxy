/**
 * Run a native tool. Returns { ok, result } or { ok: false, error }.
 */
export async function callNativeTool(name, args = {}) {
    switch (name) {
        case 'modify_ui': {
            const { zoneId, request } = args;
            if (!zoneId || !request) {
                return { ok: false, error: 'zoneId and request are required' };
            }
            if (isProtectedZoneServer(zoneId)) {
                return {
                    ok: false,
                    error: `Zone "${zoneId}" is protected (safe mode) — no live swap allowed.`,
                };
            }
            // The actual candidate component is generated by the calling agent/LLM,
            // not by this handler. This just validates and hands back a go-ahead —
            // the frontend is responsible for rendering the result through
            // ChangeConfirmGate, which does its own countdown + logging.
            return {
                ok: true,
                result: { zoneId, request, cleared: true },
            };
        }

        case 'open_chrome_profile': {
            const { profile, url } = args;
            if (!profile || !url) {
                return { ok: false, error: 'profile and url are required' };
            }
            // Accept either a raw profile string ("Profile 13" / "13") or an email
            let profileDirectory = /^\d+$/.test(profile) ? `Profile ${profile}` : profile;
            if (FAMILY_PROFILES[profile]) {
                profileDirectory = FAMILY_PROFILES[profile];
            }
            const args_ = ['-na', 'Google Chrome', '--args', `--profile-directory=${profileDirectory}`, url];
            try {
                spawn('open', args_, { detached: true, stdio: 'ignore' }).unref();
                return { ok: true, result: { profileDirectory, url, launched: true } };
            } catch (err) {
                return { ok: false, error: err.message };
            }
        }

        default:
            return { ok: false, error: `Unknown native tool: ${name}` };
    }
}
